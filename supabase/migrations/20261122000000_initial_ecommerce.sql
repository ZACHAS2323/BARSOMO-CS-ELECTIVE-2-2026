create or replace function public.place_order(items jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  item jsonb;
  product record;
  quantity integer;
  order_id uuid;
  order_total numeric(12,2) := 0;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  if coalesce(jsonb_array_length(items), 0) = 0 then
    raise exception 'Cart is empty';
  end if;

  insert into public.orders (user_id, status, total)
  values (auth.uid(), 'pending', 0)
  returning id into order_id;

  for item in select * from jsonb_array_elements(items)
  loop
    quantity := (item->>'quantity')::integer;
    if quantity <= 0 then
      raise exception 'Invalid quantity';
    end if;

    select * into product
    from public.products
    where id = (item->>'product_id')::uuid
    for update;

    if product.id is null then
      raise exception 'Product not found';
    end if;
    if product.stock < quantity then
      raise exception 'Insufficient stock for %', product.name;
    end if;

    update public.products
    set stock = stock - quantity
    where id = product.id;

    insert into public.order_items (
      order_id, product_id, product_name, quantity, unit_price
    ) values (
      order_id, product.id, product.name, quantity, product.price
    );

    order_total := order_total + product.price * quantity;
  end loop;

  update public.orders
  set total = order_total, status = 'done'
  where id = order_id;

  return jsonb_build_object(
    'order_id', order_id,
    'total', order_total,
    'status', 'done'
  );
end;
$$;

revoke execute on function public.place_order(jsonb) from public;
grant execute on function public.place_order(jsonb) to authenticated;

