create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles p
    join public.roles r on r.id = p.role_id
    where p.id = auth.uid() and r.name = 'admin'
  );
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, role_id, full_name)
  values (
    new.id,
    (select id from public.roles where name = 'customer'),
    coalesce(new.raw_user_meta_data->>'full_name', new.email)
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

insert into public.profiles (id, role_id, full_name)
select
  users.id,
  roles.id,
  coalesce(users.raw_user_meta_data->>'full_name', users.email)
from auth.users as users
cross join public.roles as roles
where roles.name = 'customer'
on conflict (id) do nothing;

create or replace function public.prevent_profile_role_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is not null
    and new.role_id is distinct from old.role_id then
    raise exception 'Users cannot change their own role';
  end if;
  return new;
end;
$$;

create trigger prevent_profile_role_change
before update on public.profiles
for each row execute function public.prevent_profile_role_change();

